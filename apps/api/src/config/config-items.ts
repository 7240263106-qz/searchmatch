export const CONFIG_ITEM_MAP: ReadonlyMap<string, ConfigItemDefinition> = new Map(
  CONFIG_ITEMS.map((entry) => [entry.key, entry]),
);

export const CONFIG_ITEM_KEYS: readonly string[] = CONFIG_ITEMS.map((entry) => entry.key);

export function configItemsOfGroup(group: ConfigGroup): ConfigItemDefinition[] {
  return CONFIG_ITEMS.filter((entry) => entry.group === group);
}

export function isConfigGroup(value: string): value is ConfigGroup {
  return (CONFIG_GROUP as readonly string[]).includes(value);
}

export function isSecuritySwitch(key: string): boolean {
  return (SECURITY_SWITCH_KEYS as readonly string[]).includes(key);
}

export function pageOfGroup(group: ConfigGroup): string {
  return CONFIG_GROUP_META[group].page;
}

export function defaultJson(definition: ConfigItemDefinition): string | null {
  return definition.defaultValue === null ? null : JSON.stringify(definition.defaultValue);
}

export function parseStoredValue(json: string | null | undefined): ConfigValue {
  if (json === null || json === undefined || json === '') return null;
  try {
    return JSON.parse(json) as ConfigValue;
  } catch {
    return json;
  }
}

export function serializeValue(value: ConfigValue): string | null {
  return value === null ? null : JSON.stringify(value);
}
